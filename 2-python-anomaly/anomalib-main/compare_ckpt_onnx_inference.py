"""Compare Anomalib Lightning checkpoint and ONNX inference.

This script is intentionally placed beside ``train.py`` so the deployment files
generated by the demo training flow can be checked with one command:

    python compare_ckpt_onnx_inference.py --ckpt model.ckpt --onnx model.onnx \
        --metadata metadata.json --input path/to/image_or_dir

It reports end-to-end checkpoint inference time, ONNX Runtime time, score/OK-NG
agreement, and anomaly-map differences. The ONNX post-processing uses the same
metadata contract consumed by TRTForge C++.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from pathlib import Path
from typing import Any

# --- 必须优先使用仓库内的 anomalib 源码 -------------------------------------
# 本脚本放在 anomalib-main 目录下，但包实际在 anomalib-main/src/anomalib，
# 所以裸 `import anomalib` 会落到 user-site（本机是 1.2.0）。而本工程的 ckpt
# 是 launcher 用仓库内源码（2.x）训练出来的，两者结构不同：
#   - ckpt 里有 `post_processor.*`，1.2.0 的模型没有该子模块 -> load_state_dict 报 unexpected
#   - 2.x 的 `Engine._setup_transform` 要求 ckpt 顶层有 `transform`
# 结果就是脚本"能跑但结果全是 0.5"。tf_anomalib_launcher.py 也是用同样的方式
# 把源码目录插到 sys.path 最前面，这里保持一致，保证与训练同一份实现。
_SRC = Path(__file__).resolve().parent / "src"
if _SRC.is_dir():
    for _p in (str(_SRC), str(_SRC.parent)):
        if _p in sys.path:
            sys.path.remove(_p)
        sys.path.insert(0, _p)

import numpy as np

