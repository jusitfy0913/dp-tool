"""Compare Anomalib Lightning checkpoint and ONNX inference.

This script is intentionally placed beside ``train.py`` so the deployment files
generated by the demo training flow can be checked with one command:

    python compare_ckpt_onnx_inference.py --ckpt model.ckpt --onnx model.onnx \
        --metadata metadata.json --input path/to/image_or_dir

It reports end-to-end checkpoint inference time, ONNX Runtime time, score/OK-NG
agreement, and anomaly-map differences. The ONNX post-processing uses the same
metadata contract consumed by TRTForge C++.
"""

from __future__ import annotations

import argparse
import csv
import json
import time
from pathlib import Path
from typing import Any

import numpy as np

from anomalib.data.utils import get_image_filenames
from anomalib.engine import Engine
from anomalib.models import EfficientAd, Patchcore
from anomalib.models.image.padim import Padim

from trtforge_metadata import (
    metadata_input_size,
    normalize_with_metadata,
    parse_anomaly_outputs,
    preprocess_image_for_onnx,
)


MODEL_FACTORIES = {
    "patchcore": Patchcore,
    "padim": Padim,
    "efficientad": EfficientAd,
}


def get_parser() -> argparse.ArgumentParser:
    """Create command-line parser."""
    parser = argparse.ArgumentParser(description="Compare model.ckpt and model.onnx inference outputs.")
    parser.add_argument("--ckpt", type=Path, required=True, help="Path to Lightning model.ckpt")
    parser.add_argument("--onnx", type=Path, required=True, help="Path to exported model.onnx")
    parser.add_argument("--metadata", type=Path, required=True, help="Path to TRTForge metadata.json")
    parser.add_argument("--input", type=Path, required=True, help="Input image or image directory")
    parser.add_argument("--output", type=Path, default=Path("compare_outputs"), help="Output directory")
    parser.add_argument(
        "--model",
        choices=sorted(MODEL_FACTORIES),
        default="patchcore",
        help="Model class used by the checkpoint.",
    )
    parser.add_argument("--device", choices=["cpu", "cuda", "auto"], default="auto", help="Lightning device")
    parser.add_argument("--onnx-provider", default="auto", help="auto/cpu/cuda")
    return parser


def _to_numpy(value: Any) -> np.ndarray | None:
    """Convert torch/numpy/scalar values to numpy."""
    if value is None:
        return None
    if hasattr(value, "detach"):
        value = value.detach().cpu()
    if hasattr(value, "numpy"):
        return np.asarray(value.numpy())
    return np.asarray(value)


def _batch_items(predictions: Any) -> list[dict[str, Any]]:
    """Flatten Anomalib prediction batches into one dict per image."""
    items: list[dict[str, Any]] = []
    if predictions is None:
        return items
    for batch in predictions:
        paths = _to_numpy(getattr(batch, "image_path", None))
        scores = _to_numpy(getattr(batch, "pred_score", None))
        labels = _to_numpy(getattr(batch, "pred_label", None))
        maps = _to_numpy(getattr(batch, "anomaly_map", None))
        batch_size = 1
        for arr in (scores, labels, maps, paths):
            if arr is not None and arr.ndim > 0:
                batch_size = int(arr.shape[0])
                break
        for idx in range(batch_size):
            def pick(arr: np.ndarray | None) -> Any:
                if arr is None:
                    return None
                if arr.ndim == 0:
                    return arr.item()
                return arr[idx]

            path_value = pick(paths)
            if isinstance(path_value, bytes):
                path_value = path_value.decode("utf-8", errors="ignore")
            items.append(
                {
                    "image_path": str(path_value) if path_value is not None else "",
                    "score": float(np.ravel(pick(scores))[0]) if scores is not None else 0.0,
                    "label": bool(np.ravel(pick(labels))[0]) if labels is not None else False,
                    "map": np.asarray(pick(maps), dtype=np.float32) if maps is not None else None,
                },
            )
    return items


def _load_metadata(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _onnx_providers(choice: str) -> list[str]:
    if choice == "cpu":
        return ["CPUExecutionProvider"]
    if choice == "cuda":
        return ["CUDAExecutionProvider", "CPUExecutionProvider"]
    return ["CUDAExecutionProvider", "CPUExecutionProvider"]


def run_ckpt(args: argparse.Namespace, filenames: list[Path]) -> tuple[list[dict[str, Any]], float]:
    """Run Lightning checkpoint prediction once for the complete input set."""
    model = MODEL_FACTORIES[args.model]()
    accelerator = "auto"
    if args.device == "cpu":
        accelerator = "cpu"
    elif args.device == "cuda":
        accelerator = "gpu"
    engine = Engine(accelerator=accelerator, devices=1)

    start = time.perf_counter()
    predictions = engine.predict(
        model=model,
        data_path=args.input,
        ckpt_path=args.ckpt,
        return_predictions=True,
    )
    total_ms = (time.perf_counter() - start) * 1000.0
    items = _batch_items(predictions)
    if len(items) != len(filenames):
        # Keep row alignment deterministic even when prediction batches do not expose paths.
        for item, filename in zip(items, filenames, strict=False):
            item["image_path"] = str(filename)
    return items, total_ms


def run_onnx(args: argparse.Namespace, metadata: dict[str, Any], filenames: list[Path]) -> list[dict[str, Any]]:
    """Run ONNX Runtime once per image with a reused session."""
    import onnxruntime as ort

    session = ort.InferenceSession(str(args.onnx), providers=_onnx_providers(args.onnx_provider))
    input_name = session.get_inputs()[0].name
    output_names = [output.name for output in session.get_outputs()]
    results: list[dict[str, Any]] = []
    image_threshold = float(metadata.get("image_threshold", 0.5))
    pixel_threshold = float(metadata.get("pixel_threshold", 0.5))
    score_range = metadata.get("pred_scores", {})
    map_range = metadata.get("anomaly_maps", {})
    score_min = float(metadata.get("pred_scores.min", score_range.get("min", 0.0)))
    score_max = float(metadata.get("pred_scores.max", score_range.get("max", 1.0)))
    map_min = float(metadata.get("anomaly_maps.min", map_range.get("min", 0.0)))
    map_max = float(metadata.get("anomaly_maps.max", map_range.get("max", 1.0)))

    for filename in filenames:
        tensor = preprocess_image_for_onnx(filename, metadata, args.model)
        start = time.perf_counter()
        outputs = session.run(None, {input_name: tensor})
        elapsed_ms = (time.perf_counter() - start) * 1000.0
        raw_score, raw_map = parse_anomaly_outputs(outputs, output_names)
        normalized_score = float(normalize_with_metadata(raw_score, image_threshold, score_min, score_max))
        normalized_map = normalize_with_metadata(raw_map, pixel_threshold, map_min, map_max) if raw_map is not None else None
        results.append(
            {
                "image_path": str(filename),
                "score": normalized_score,
                "raw_score": raw_score,
                "label": normalized_score >= 0.5,
                "map": normalized_map,
                "elapsed_ms": elapsed_ms,
            },
        )
    return results


def _map_diff(ckpt_map: np.ndarray | None, onnx_map: np.ndarray | None) -> tuple[float, float]:
    if ckpt_map is None or onnx_map is None:
        return 0.0, 0.0
    ckpt_arr = np.squeeze(ckpt_map).astype(np.float32)
    onnx_arr = np.squeeze(onnx_map).astype(np.float32)
    if ckpt_arr.shape != onnx_arr.shape:
        from PIL import Image

        image = Image.fromarray(onnx_arr)
        image = image.resize((ckpt_arr.shape[-1], ckpt_arr.shape[-2]))
        onnx_arr = np.asarray(image, dtype=np.float32)
    diff = np.abs(ckpt_arr - onnx_arr)
    return float(np.mean(diff)), float(np.max(diff))


def write_report(args: argparse.Namespace, filenames: list[Path], ckpt_items: list[dict[str, Any]], onnx_items: list[dict[str, Any]], ckpt_total_ms: float) -> Path:
    """Write compare_results.csv."""
    args.output.mkdir(parents=True, exist_ok=True)
    report = args.output / "compare_results.csv"
    ckpt_avg_ms = ckpt_total_ms / max(1, len(filenames))
    with report.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "image",
                "ckpt_ms_avg",
                "onnx_ms",
                "ckpt_score",
                "onnx_score",
                "score_abs_diff",
                "ckpt_status",
                "onnx_status",
                "status_match",
                "map_mean_abs_diff",
                "map_max_abs_diff",
            ],
        )
        writer.writeheader()
        for filename, ckpt, onnx in zip(filenames, ckpt_items, onnx_items, strict=False):
            map_mean, map_max = _map_diff(ckpt.get("map"), onnx.get("map"))
            ckpt_score = float(ckpt.get("score", 0.0))
            onnx_score = float(onnx.get("score", 0.0))
            ckpt_status = "NG" if ckpt.get("label") else "OK"
            onnx_status = "NG" if onnx.get("label") else "OK"
            writer.writerow(
                {
                    "image": str(filename),
                    "ckpt_ms_avg": f"{ckpt_avg_ms:.3f}",
                    "onnx_ms": f"{float(onnx.get('elapsed_ms', 0.0)):.3f}",
                    "ckpt_score": f"{ckpt_score:.6f}",
                    "onnx_score": f"{onnx_score:.6f}",
                    "score_abs_diff": f"{abs(ckpt_score - onnx_score):.6f}",
                    "ckpt_status": ckpt_status,
                    "onnx_status": onnx_status,
                    "status_match": ckpt_status == onnx_status,
                    "map_mean_abs_diff": f"{map_mean:.6f}",
                    "map_max_abs_diff": f"{map_max:.6f}",
                },
            )
    return report


def main() -> None:
    args = get_parser().parse_args()
    metadata = _load_metadata(args.metadata)
    input_h, input_w = metadata_input_size(metadata)
    filenames = [Path(p) for p in get_image_filenames(args.input)]
    if not filenames:
        raise FileNotFoundError(f"未找到可推理图片：{args.input}")
    print(f"input images: {len(filenames)}")
    print(f"metadata input size: {input_w}x{input_h}")

    ckpt_items, ckpt_total_ms = run_ckpt(args, filenames)
    onnx_items = run_onnx(args, metadata, filenames)
    report = write_report(args, filenames, ckpt_items, onnx_items, ckpt_total_ms)
    print(f"ckpt total: {ckpt_total_ms:.3f} ms, avg: {ckpt_total_ms / max(1, len(filenames)):.3f} ms")
    print(f"report    : {report.resolve()}")


if __name__ == "__main__":
    main()
